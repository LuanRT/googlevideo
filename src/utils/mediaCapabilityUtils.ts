export const surroundAudioCodes: Set<string> = new Set([ 'm', 'M', 'mac3', 'MAC3', 'meac3', 'MEAC3', 'i', 'I' ]);

export function buildAudioCapability(
  format: SabrFormat,
  isSurroundSupported = true
): AudioFormatCapability | undefined {
  const codecCode = format.codecCode;

  if (!codecCode || codecCode === 'f') return undefined;
  if (!isSurroundSupported && surroundAudioCodes.has(codecCode)) return undefined;

  return {
    audioCodec: AUDIO_CODECS[codecCode as keyof typeof AUDIO_CODECS],
    spatialCapabilityBitmask: SPATIAL_AUDIO_CODECS[codecCode as keyof typeof SPATIAL_AUDIO_CODECS],
    numChannels: format.numChannels
  };
}

export function buildVideoCapability(format: SabrFormat): VideoFormatCapability | undefined {
  const codecCode = format.codecCode;

  if (!codecCode || codecCode === 'f') return undefined;

  return {
    videoCodec: VIDEO_CODECS[codecCode as keyof typeof VIDEO_CODECS],
    maxWidth: format.width || 0,
    maxHeight: format.height || 0,
    maxFramerate: format.fps || 0,
    is10BitSupported: !!format.isHdr,
    maxBitrateBps: format.bitrate || 0,
    efficient: true
  };
}

export function buildMediaCapabilities(
  videoFormat?: SabrFormat,
  audioFormat?: SabrFormat,
  isSurroundSupported = true
): MediaCapabilities | undefined {
  // In the official client, this function does some kind of filtering & sorting.
  // Since we only care about two formats here, we don't have to do any of that.
  const video = videoFormat ? buildVideoCapability(videoFormat) : undefined;
  const audio = audioFormat ? buildAudioCapability(audioFormat, isSurroundSupported) : undefined;

  if (!video && !audio) return undefined;

  return {
    videoFormatCapabilities: video ? [ video ] : [],
    audioFormatCapabilities: audio ? [ audio ] : [],
    hdrModeBitmask: 3
  };
}